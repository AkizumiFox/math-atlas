"""Write registry/chapter-constraints.yaml into analysis-book's blueprint/book.yaml, one way.

The atlas file is the only source. In book.yaml the constraints live in one block between BEGIN and END markers,
marked as generated; it records the atlas commit the constraints come from, so each constraint has a version.
Nobody edits the block by hand: atlas.py check compares it with the atlas file and fails on any drift.

    python3 tools/sync_constraints.py           # report drift (exit 1 if the block is stale)
    python3 tools/sync_constraints.py --write   # rewrite the block (chapter-constraints.yaml must be committed)
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "registry" / "chapter-constraints.yaml"
BOOK = ROOT.parent / "analysis-book" / "blueprint" / "book.yaml"
BEGIN = "# >>> atlas-constraints: generated by math-atlas tools/sync_constraints.py; do not edit by hand"
END = "# <<< atlas-constraints"


HAN = r"[\u2e80-\u2fff\u3400-\u9fff]"
PUNCT = r"[\u3000-\u303f\uff00-\uffef]"


def tidy(text):
    """Undo the spaces YAML folding leaves where a line broke inside Chinese text: between two Chinese characters or
    next to full-width punctuation. Spaces between Chinese and Latin text are house style and stay."""
    text = re.sub(rf"(?<={HAN})\s+(?={HAN})|(?<={PUNCT})\s+|\s+(?={PUNCT})", "", str(text).strip())
    return re.sub(r"\s+", " ", text)


def wanted(constraints):
    """{analysis-book chapter number: [constraint, ...]} for the constraints on analysis-book chapters."""
    out = {}
    for k in constraints:
        m = re.fullmatch(r"ab:(\d+)", str(k.get("book")))
        if m:
            row = {"atlas": k["chapter"], "decided": str(k["decided"]), "rule": tidy(k["rule"])}
            if k.get("why"):
                row["why"] = tidy(k["why"])
            out.setdefault(int(m.group(1)), []).append(row)
    return dict(sorted(out.items()))


def current(text):
    """The block's (commit, chapters), or None when book.yaml has no block."""
    if BEGIN not in text:
        return None
    body = text[text.index(BEGIN) + len(BEGIN):text.index(END)]
    data = (yaml.safe_load(body) or {}).get("atlas_constraints") or {}
    return data.get("source"), {int(k): v for k, v in (data.get("chapters") or {}).items()}


def drift(constraints, book=BOOK):
    """None when book.yaml agrees with the atlas, else a one-line reason. Missing repo: None (nothing to check)."""
    if not book.exists():
        return None
    got = current(book.read_text())
    if got is None:
        return f"{book} has no atlas-constraints block; run tools/sync_constraints.py --write"
    if got[1] != wanted(constraints):
        return (f"{book}: the atlas-constraints block (from {got[0]}) differs from registry/chapter-constraints.yaml; "
                "rerun tools/sync_constraints.py --write, never edit the block by hand")
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--book", type=Path, default=BOOK, help="book.yaml to check or write (default: ../analysis-book)")
    args = ap.parse_args()
    constraints = yaml.safe_load(SRC.read_text()) or []
    if not args.write:
        reason = drift(constraints, args.book)
        print(reason or "book.yaml is in sync")
        sys.exit(1 if reason else 0)
    rel = str(SRC.relative_to(ROOT))
    if subprocess.run(["git", "diff", "--quiet", "HEAD", "--", rel], cwd=ROOT).returncode:
        sys.exit(f"{rel} has uncommitted changes; commit them first so the block can name a commit")
    commit = subprocess.run(["git", "log", "-1", "--format=%h", "--", rel], cwd=ROOT,
                            capture_output=True, text=True, check=True).stdout.strip()
    body = yaml.safe_dump({"atlas_constraints": {"source": f"math-atlas@{commit} {rel}", "chapters": wanted(constraints)}},
                          allow_unicode=True, sort_keys=False, width=110)
    block = f"{BEGIN}\n{body}{END}\n"
    text = args.book.read_text()
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END) + 1:]
    else:
        text = text.rstrip("\n") + "\n\n" + block
    args.book.write_text(text)
    print(f"wrote the atlas-constraints block (math-atlas@{commit}) into {args.book}")


if __name__ == "__main__":
    main()
