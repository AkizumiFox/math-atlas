"""Collect the labels of every book and find the ones defined in more than one book.

Statement ids are series-wide (spec/01): the same `kind-slug` must not name two different results in two books.
Reads <book>/_build/crossref_labels.json for each book in BOOKS and writes registry/computed/labels.yaml:
  duplicates: [[label, [[book, chapter], ...]], ...]   labels defined in more than one book
  statements: {statement id: [[book, chapter], ...]}   where each registry/statements.yaml id occurs in the books
chapter is the atlas chapter of the section (None when the book has no atlas chapters yet).
"""
import json
import re
from collections import defaultdict
from pathlib import Path

import yaml

import import_la

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "registry" / "computed" / "labels.yaml"
BOOKS = {"la": "linear-algebra", "ab": "analysis-book", "rg": "regression"}


def ab_chapter(chapters):
    src = {}
    for vid, chs in chapters.items():
        for ch in chs:
            for s in ch["src"] if isinstance(ch["src"], list) else [ch["src"]]:
                m = re.match(r"ab:(\d+)", str(s))
                if m:
                    src.setdefault(int(m.group(1)), ch["id"])

    def where(path):
        m = re.match(r"ch(\d+)", path or "")
        return src.get(int(m.group(1))) if m else None
    return where


class NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def main():
    chapters = yaml.safe_load((ROOT / "registry" / "chapters.yaml").read_text())
    locate = {"la": import_la.atlas_chapter, "ab": ab_chapter(chapters), "rg": lambda path: None}
    found = defaultdict(list)
    for book, repo in BOOKS.items():
        path = ROOT.parent / repo / "_build" / "crossref_labels.json"
        if not path.exists():
            print(f"warning: {path} not found; skipping {book}")
            continue
        for label, rec in json.loads(path.read_text())["crossref_labels"].items():
            found[label].append([book, locate[book](rec.get("file"))])
    stmt = [n[0] for n in yaml.safe_load((ROOT / "registry" / "statements.yaml").read_text())["nodes"]]
    dup = [[k, v] for k, v in sorted(found.items()) if len({b for b, _ in v}) > 1]
    body = {"duplicates": dup, "statements": {s: found[s] for s in stmt if s in found}}
    OUT.write_text("# Generated by tools/import_labels.py from each book's _build/crossref_labels.json; do not edit.\n"
                   + yaml.dump(body, Dumper=NoAliases, allow_unicode=True, sort_keys=False, default_flow_style=None, width=200))
    print(f"{len(found)} labels, {len(dup)} defined in more than one book -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
